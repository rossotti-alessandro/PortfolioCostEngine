#!/usr/bin/env node
/**
 * @module scripts/backlog-board
 *
 * Generates `backlog/BOARD.md`, the one-page view of the backlog:
 *   - Active work: every In Progress / In Review / Blocked story with owner, model, branch, progress.
 *     Rows with no owner are flagged (nobody is actually on them).
 *   - Ready to claim: To Do stories whose dependencies are all Done, by priority.
 *   - Epics: % done computed from their stories (never hand-set).
 *
 * Story progress: explicit `progress:` wins; otherwise Done = 100, In Review = 90,
 * In Progress/Blocked = share of ticked acceptance criteria (max 80), To Do = 0.
 *
 * Usage:
 *   node scripts/backlog-board.mjs            # write backlog/BOARD.md (run on main after merges)
 *   node scripts/backlog-board.mjs --stdout   # print instead of writing
 *   node scripts/backlog-board.mjs --epic 7   # print one epic's stories
 *   node scripts/backlog-board.mjs --ready    # print claimable stories only
 */

import { writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { STATUSES, idNum, loadTasks, normId } from "./lib/backlog-frontmatter.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const tasks = loadTasks(join(root, "backlog/tasks")).map((t) => ({
  ...t,
  id: normId(t.data.id),
  title: String(t.data.title || "").replace(/\|/g, "/"),
  status: t.data.status || "To Do",
  parent: normId(t.data.parent_task_id && t.data.parent_task_id !== "null" ? t.data.parent_task_id : ""),
  labels: Array.isArray(t.data.labels) ? t.data.labels : [],
  deps: (Array.isArray(t.data.dependencies) ? t.data.dependencies : []).map(normId),
  priority: t.data.priority || "P2",
}));
const byId = new Map(tasks.map((t) => [t.id, t]));
const children = new Map();
for (const t of tasks) {
  if (!t.parent || !byId.has(t.parent)) continue;
  if (!children.has(t.parent)) children.set(t.parent, []);
  children.get(t.parent).push(t);
}
const isEpic = (t) => t.labels.includes("epic") || children.has(t.id);

/** Progress 0-100 for one story. */
function storyProgress(t) {
  const explicit = Number(t.data.progress);
  if (t.data.progress !== undefined && t.data.progress !== "" && Number.isFinite(explicit)) return explicit;
  if (t.status === "Done") return 100;
  if (t.status === "In Review") return 90;
  if (t.status === "In Progress" || t.status === "Blocked") {
    const ticked = (t.body.match(/^- \[x\]/gim) || []).length;
    const total = ticked + (t.body.match(/^- \[ \]/gm) || []).length;
    return total ? Math.min(80, Math.round((ticked / total) * 80)) : 10;
  }
  return 0;
}

/** Progress for an epic: mean of its stories (recursive). */
function epicProgress(id, seen = new Set()) {
  if (seen.has(id)) return 0;
  seen.add(id);
  const kids = children.get(id) || [];
  if (!kids.length) return storyProgress(byId.get(id));
  const sum = kids.reduce((a, k) => a + (children.has(k.id) ? epicProgress(k.id, seen) : storyProgress(k)), 0);
  return Math.round(sum / kids.length);
}

const bar = (p) => `${"█".repeat(Math.round(p / 10))}${"░".repeat(10 - Math.round(p / 10))} ${String(p).padStart(3)}%`;
const link = (t) => `[${t.id}](tasks/${encodeURI(t.file)})`;
const byNum = (a, b) => {
  const x = idNum(a.id).split(".").map(Number);
  const y = idNum(b.id).split(".").map(Number);
  for (let i = 0; i < Math.max(x.length, y.length); i++) if ((x[i] || 0) !== (y[i] || 0)) return (x[i] || 0) - (y[i] || 0);
  return 0;
};
const ready = tasks
  .filter((t) => !isEpic(t) && t.status === "To Do" && !t.data.owner)
  .filter((t) => t.deps.every((d) => byId.get(d)?.status === "Done"))
  .sort((a, b) => a.priority.localeCompare(b.priority) || byNum(a, b));

const arg = (k) => process.argv.indexOf(k);
if (arg("--epic") > 0) {
  const id = normId(process.argv[arg("--epic") + 1]);
  const e = byId.get(id);
  if (!e) throw new Error(`no epic ${id}`);
  console.log(`${e.id} ${e.title}  ${bar(epicProgress(id))}`);
  for (const k of (children.get(id) || []).sort(byNum)) {
    console.log(`  ${k.id.padEnd(9)} ${k.status.padEnd(12)} ${bar(storyProgress(k))}  ${k.data.owner || "-"}  ${k.title}`);
  }
  process.exit(0);
}
if (arg("--ready") > 0) {
  for (const t of ready) console.log(`${t.id.padEnd(9)} ${t.priority}  ${t.title}`);
  process.exit(0);
}

const active = tasks.filter((t) => ["In Progress", "In Review", "Blocked"].includes(t.status)).sort(byNum);
const epics = tasks.filter(isEpic).sort(byNum);
const counts = tasks.filter((t) => !isEpic(t)).reduce((a, t) => ((a[t.status] = (a[t.status] || 0) + 1), a), {});
const out = [
  "# Backlog board",
  "",
  "> Generated by `node scripts/backlog-board.mjs`. Do not edit by hand. Regenerated on `main` after each merge",
  "> (never on a story branch: it would conflict). Protocol: [AGENTS.md](../AGENTS.md), [.claude/rules/task-lifecycle.md](../.claude/rules/task-lifecycle.md).",
  "",
  `**${tasks.length - epics.length} stories in ${epics.length} epics** · ${STATUSES.map((s) => `${s}: ${counts[s] || 0}`).join(" · ")}`,
  "",
  "## Active work",
  "",
  "Rows marked ⚠ have no owner: treat them as unclaimed.",
  "",
  "| Story | Title | Status | Owner | Model | Progress | Branch / PR |",
  "| --- | --- | --- | --- | --- | --- | --- |",
  ...active.map((t) => {
    const where = [t.data.branch && `\`${t.data.branch}\``, t.data.pr].filter(Boolean).join(" ") || "-";
    return `| ${link(t)} | ${t.title} | ${t.status} | ${t.data.owner || "⚠ none"} | ${t.data.model || "-"} | \`${bar(storyProgress(t))}\` | ${where} |`;
  }),
  "",
  "## Ready to claim",
  "",
  "To Do, unowned, every dependency Done. Highest priority first.",
  "",
  "| Story | Priority | Title | Epic |",
  "| --- | --- | --- | --- |",
  ...ready.map((t) => `| ${link(t)} | ${t.priority} | ${t.title} | ${t.parent || "-"} |`),
  "",
  "## Epics",
  "",
  "| Epic | Title | Stories done | Progress |",
  "| --- | --- | --- | --- |",
  ...epics.map((e) => {
    const kids = children.get(e.id) || [];
    return `| ${link(e)} | ${e.title} | ${kids.filter((k) => k.status === "Done").length}/${kids.length} | \`${bar(epicProgress(e.id))}\` |`;
  }),
  "",
  "One epic: `node scripts/backlog-board.mjs --epic <id>`. Claimable list: `node scripts/backlog-board.mjs --ready`.",
  "",
];
const text = out.join("\n");
if (process.argv.includes("--stdout")) console.log(text);
else {
  writeFileSync(join(root, "backlog/BOARD.md"), text);
  console.log(`✓ backlog/BOARD.md (${active.length} active, ${ready.length} ready, ${epics.length} epics)`);
}
