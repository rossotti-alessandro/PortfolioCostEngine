"""Coverage matrix of the specimen corpus: document type x language x institution.

Usage (from the repo root, stdlib only):
    python3 data/specimens/tools/coverage.py      # writes data/specimens/COVERAGE.md
"""

from __future__ import annotations

import csv
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
MANIFEST = ROOT / "data" / "reference" / "specimen_corpus.csv"
OUT = ROOT / "data" / "specimens" / "COVERAGE.md"
LANGS = ["de", "it", "fr", "en", "other"]


def table(rows: list[dict], key: str) -> list[str]:
    counts: dict[str, Counter] = defaultdict(Counter)
    issuers: dict[str, set] = defaultdict(set)
    for r in rows:
        lang = r["language"] if r["language"] in LANGS else "other"
        counts[r[key]][lang] += 1
        issuers[r[key]].add(r["issuer"].strip().lower())
    out = [
        f"| {key.replace('_', ' ').capitalize()} | " + " | ".join(LANGS) + " | Total | Institutions |",
        "|---|" + "---|" * (len(LANGS) + 2),
    ]
    for k in sorted(counts, key=lambda k: -sum(counts[k].values())):
        c = counts[k]
        out.append(
            f"| {k} | "
            + " | ".join(str(c[lang] or "·") for lang in LANGS)
            + f" | {sum(c.values())} | {len(issuers[k])} |"
        )
    tot = Counter(r["language"] if r["language"] in LANGS else "other" for r in rows)
    out.append(
        "| **All** | "
        + " | ".join(str(tot[lang]) for lang in LANGS)
        + f" | {len(rows)} | {len({r['issuer'].strip().lower() for r in rows})} |"
    )
    return out


def main() -> None:
    rows = list(csv.DictReader(MANIFEST.open(encoding="utf-8")))
    juris = Counter(r["jurisdiction"] for r in rows)
    lines = [
        "# Specimen corpus: coverage",
        "",
        "Generated by `data/specimens/tools/coverage.py` from `data/reference/specimen_corpus.csv`. "
        "Do not edit by hand.",
        "",
        "## By category and language",
        "",
        *table(rows, "category"),
        "",
        "## By taxonomy code and language",
        "",
        *table(rows, "document_type"),
        "",
        "## By jurisdiction",
        "",
        ", ".join(f"{k or '?'} {v}" for k, v in juris.most_common()),
        "",
        "## Institutions per category",
        "",
    ]
    by_cat: dict[str, Counter] = defaultdict(Counter)
    for r in rows:
        by_cat[r["category"]][r["issuer"].strip()] += 1
    for cat in sorted(by_cat):
        names = ", ".join(f"{n} ({c})" if c > 1 else n for n, c in sorted(by_cat[cat].items()))
        lines.append(f"- **{cat}**: {names}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(rows)} files")


if __name__ == "__main__":
    main()
