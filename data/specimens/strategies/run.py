"""Run every extraction strategy on the hand-checked benchmark pages and score them (SC-5.8).

Pages, ground truth and stored engine outputs come from the SC-5.6 benchmark
(``data/specimens/ocrbench``; outputs in ``var/ocrbench/out/<engine>/<page>.json``). Production code
paths (``pce.extraction``) run live; slow models are not re-run: their stored outputs are reused and
their stored time is added to the strategy's time.

Usage (repo root):  cd backend && uv run python ../data/specimens/strategies/run.py [--only name,...]
Writes data/specimens/strategies/RESULTS.md and var/strategies/<strategy>.json (predictions).
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from collections.abc import Callable
from pathlib import Path

HERE = Path(__file__).parent
ROOT = HERE.parents[2]
sys.path.insert(0, str(HERE))
import score  # noqa: E402
import strategies as S  # noqa: E402

BENCH = ROOT / "data" / "specimens" / "ocrbench"
OUT = ROOT / "var" / "strategies"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", default="")
    ap.add_argument("--pages", default="all", choices=["all", "core"])
    args = ap.parse_args()
    pages = json.loads((BENCH / "pages.json").read_text(encoding="utf-8"))
    gold = json.loads((BENCH / "groundtruth.json").read_text(encoding="utf-8"))["pages"]
    core = set(json.loads((BENCH / "vlm_core.json").read_text(encoding="utf-8")))
    OUT.mkdir(parents=True, exist_ok=True)
    chosen: dict[str, Callable] = {
        k: v for k, v in S.STRATEGIES.items() if not args.only or k in args.only.split(",")
    }
    results: dict[str, dict] = {}
    for name, fn in chosen.items():
        per_page, secs, dump = {}, [], {}
        for p in pages:
            if args.pages == "core" and p["id"] not in core:
                continue
            g = gold.get(p.get("gt_from") or p["id"])
            if g is None:
                continue
            t0 = time.perf_counter()
            out = fn(p)
            if out is None:  # strategy does not cover this page (no stored output): left out, not zero
                continue
            preds, extra_s = out
            secs.append(time.perf_counter() - t0 + extra_s)
            per_page[p["id"]] = score.score_page(g["items"], preds)
            dump[p["id"]] = preds
        if not per_page:
            continue
        results[name] = {"summary": score.summarise(per_page, secs), "pages": per_page}
        (OUT / f"{name}.json").write_text(json.dumps(dump, indent=1, ensure_ascii=False, default=str))
        s = results[name]["summary"]
        print(
            f"{name:<28} pages {s['pages']:>2} P {s['precision']:.2f} R {s['recall']:.2f} F1 {s['f1']:.2f} "
            f"wrong {s['wrong_share']:.1%} review {s['review_share']:.0%} "
            f"acc-wrong {s['wrong_accepted_share']:.1%} "
            f"bbox {s['bbox_hit_rate']:.0%} {s['s_per_page']:.2f}s",
            flush=True,
        )
    prev = OUT / "scores.json"
    merged = json.loads(prev.read_text()) if prev.exists() and args.only else {}
    merged.update({f"{k}@{args.pages}": v for k, v in results.items()})
    prev.write_text(json.dumps(merged, indent=1))
    write_md(merged)


def write_md(results: dict) -> None:
    head = (
        "| Strategy | Pages | Gold fees | Predictions | Precision | Recall | F1 | Value-only recall | "
        "Wrong values | Needs review | Precision (accepted) | Wrong (accepted) | Bbox hit | s/page |\n"
        "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|\n"
    )
    out = [
        "# Extraction strategies — scores\n",
        "Generated by `data/specimens/strategies/run.py` on the SC-5.6 hand-checked pages "
        "(`data/specimens/ocrbench/groundtruth.json`). Matching rules: see `score.py`. "
        "*Wrong values*: predictions whose label matches a printed fee but whose value does not, plus "
        "unmatched zeros (share of predictions). *(accepted)*: only predictions not flagged needs_review. "
        "s/page: median, CPU, includes the stored time of any model output reused.\n",
    ]
    for scope, title in (("all", "All 44 pages"), ("core", "The 23 core pages every VLM ran on")):
        rows = {k.rsplit("@", 1)[0]: v["summary"] for k, v in results.items() if k.endswith("@" + scope)}
        if not rows:
            continue
        out.append(f"\n## {title}\n\n" + head)
        for k, s in sorted(rows.items(), key=lambda kv: -kv[1]["f1"]):
            out.append(
                f"| {k} | {s['pages']} | {s['gold']} | {s['pred']} | "
                f"{s['precision']:.0%} | {s['recall']:.0%} | "
                f"{s['f1']:.2f} | {s['value_recall']:.0%} | {s['wrong']} ({s['wrong_share']:.1%}) | "
                f"{s['review_share']:.0%} | {s['accepted_precision']:.0%} | {s['wrong_accepted']} "
                f"({s['wrong_accepted_share']:.1%}) | {s['bbox_hit_rate']:.0%} | {s['s_per_page']:.2f} |\n"
            )
    (HERE / "RESULTS.md").write_text("".join(out), encoding="utf-8")


if __name__ == "__main__":
    main()
