"""Run the SYNTHETIC prospects through the FeeLens app end to end, for the lab's "App end to end" view (SC-5.7).

For each synthetic prospect (P-1042, P-2077) and each variant (born-digital, and image-only "scan" copies
that force the OCR path) this does what the app does after an upload: extract every document with the
production pipeline, run ``pce.analysis.analyse`` on all facts, and keep the cost lines with the facts
they cite. The accuracy protocol (``pce.evaluation``, SC-9.1) scores the same run against the totals
pinned by hand, so the lab shows the app's numbers, the expected numbers and every check side by side.
Each counted cost line keeps its source: document, page and box, so the viewer can open the page.

Documents are SYNTHETIC (generated by ``demo/generate.py`` and ``demo/archetypes.py``); no client data.

Runs in the backend environment:
    cd backend && uv run python ../data/specimens/ocrbench/app_e2e.py
Writes var/ocrbench/e2e/e2e.json and var/ocrbench/e2e/img/ (git-ignored).
"""

from __future__ import annotations

import json
import shutil
from decimal import Decimal
from pathlib import Path

import pypdfium2 as pdfium

from pce.analysis import analyse
from pce.demo import spec
from pce.evaluation import runner
from pce.evaluation.strategies import baseline

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / "var" / "ocrbench" / "e2e"
SCALE = 1.5  # page images at 108 dpi; boxes are PDF points x SCALE
RUNS = [("synthetic-p1042", "digital"), ("synthetic-p1042", "scan"), ("synthetic-p2077", "digital"),
        ("synthetic-p2077", "scan")]  # fmt: skip
METRICS = ("recall", "precision", "wrong_value", "missing_as_zero", "missed", "gold", "provenance",
           "portfolio_mismatches", "portfolio", "alarms", "silent_error", "invariant_failures", "invariants",
           "needs_review_share", "median_seconds_per_page")  # fmt: skip


def render(path: Path, data: bytes, key: str) -> list[dict]:
    """JPEG of every page of a PDF (as the app received it), with its size in image pixels."""
    if not path.name.lower().endswith(".pdf"):
        return []
    pages = []
    doc = pdfium.PdfDocument(data)
    for i, page in enumerate(doc):
        img = page.render(scale=SCALE).to_pil().convert("RGB")
        name = f"{key}-{i + 1}.jpg"
        img.save(OUT / "img" / name, "JPEG", quality=70, optimize=True)
        pages.append({"img": f"e2e/img/{name}", "w": img.size[0], "h": img.size[1]})
    return pages


def run(corpus_name: str, variant: str) -> dict:
    corpus = runner.load_corpus(corpus_name, OUT / "files")
    scored = runner.evaluate(corpus, "baseline", variant)  # the protocol's own scoring of this run
    documents, facts, docs_view = [], [], []
    fid = 0
    for i, gd in enumerate(corpus.docs, start=1):
        path = corpus.folder / gd.file
        data = path.read_bytes()
        if variant == "scan":
            data = runner.as_scan(gd.file, data)
        pred = baseline(gd.file, data)
        documents.append({"id": i, "filename": gd.file, "doc_type": pred.doc_type, "profile": pred.profile})
        key = f"{corpus_name}-{variant}-{i}"
        docs_view.append({"id": i, "file": gd.file, "doc_type": pred.doc_type, "pages": render(path, data, key)})
        for f in pred.facts:
            fid += 1
            facts.append({**f, "id": fid, "document_id": i, "status": "extracted"})
    a = analyse({"domicile": corpus.domicile}, documents, facts, spec.PROPOSAL_DEFAULTS)
    by_id = {f["id"]: f for f in facts}

    def source(i: int) -> dict:
        f = by_id[i]
        ev = f.get("evidence") or {}
        return {"doc": f["document_id"], "label": f["label"], "value": f.get("value"), "kind": f["kind"],
                "page": ev.get("page"), "b": [v * SCALE for v in ev["bbox"]] if ev.get("bbox") else None,
                "sheet": ev.get("sheet"), "cell": ev.get("cell"), "snippet": (ev.get("snippet") or "")[:200],
                "engine": ev.get("engine")}  # fmt: skip

    ledger = a["current"]  # the client's current all-in cost; "internal" (our margin) is never copied out
    atoms = ledger["atoms"]
    for at in atoms:
        at["sources"] = [source(i) for i in at.get("evidence_fact_ids", []) if i in by_id]
    expect = {k: str(v) for k, v in (corpus.portfolio.expect.items() if corpus.portfolio else [])}
    return {
        "corpus": corpus_name,
        "variant": variant,
        "metrics": {k: scored.get(k) for k in METRICS},
        "per_document": scored.get("per_document", []),
        "expect": expect,
        "got": {k: str(runner._get(a, k)) for k in expect},
        "aum": a["aum"]["total"],
        "summary": {k: v for k, v in ledger.items() if k != "atoms"},
        "atoms": atoms,
        "checks": a.get("checks", []),
        "requests": a.get("requests", []),
        "docs": docs_view,
    }


def main() -> None:
    if OUT.exists():
        shutil.rmtree(OUT)
    (OUT / "img").mkdir(parents=True)
    runs = []
    for c, v in RUNS:
        r = run(c, v)
        m = r["metrics"]
        print(f"{c} {v}: recall {m['recall']} precision {m['precision']} mismatches {m['portfolio_mismatches']}")
        runs.append(r)
    blob = json.dumps({"runs": runs}, ensure_ascii=False, default=lambda o: str(o) if isinstance(o, Decimal) else None)
    (OUT / "e2e.json").write_text(blob, encoding="utf-8")


if __name__ == "__main__":
    main()
